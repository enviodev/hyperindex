#[derive(Clone, Debug)]
struct Param {
    name: String,
    ty: String,
    indexed: bool,
    components: Vec<Param>,
}

#[derive(Debug)]
struct Entry {
    kind: Option<String>,
    name: Option<String>,
    inputs: Vec<Param>,
    outputs: Vec<Param>,
    mutability: Option<String>,
    constant: Option<bool>,
    payable: bool,
}

struct Abi {
    /// Sanitized into a class name, as graph-cli does.
    name: String,
    entries: Vec<Entry>,
}

fn parse_params(json: Option<&Json>) -> Vec<Param> {
    json.and_then(Json::as_array)
        .map(|params| {
            params
                .iter()
                .map(|param| Param {
                    name: param
                        .get("name")
                        .and_then(Json::as_str)
                        .unwrap_or("")
                        .to_string(),
                    ty: param
                        .get("type")
                        .and_then(Json::as_str)
                        .unwrap_or("")
                        .to_string(),
                    indexed: param
                        .get("indexed")
                        .and_then(Json::as_bool)
                        .unwrap_or(false),
                    components: parse_params(param.get("components")),
                })
                .collect()
        })
        .unwrap_or_default()
}

fn load_abi(name: &str, file: &Path) -> Result<Abi> {
    let text = std::fs::read_to_string(file)
        .with_context(|| format!("reading the ABI {}", file.display()))?;
    let json: Json = serde_json::from_str(&text)
        .with_context(|| format!("Could not parse ABI {}", file.display()))?;
    let array = match &json {
        Json::Array(array) => Some(array),
        other => other
            .get("abi")
            .or_else(|| other.get("compilerOutput").and_then(|c| c.get("abi")))
            .and_then(Json::as_array),
    }
    .ok_or_else(|| anyhow!("No valid ABI in file: {}", file.display()))?;
    let entries = array
        .iter()
        .map(|entry| Entry {
            kind: entry.get("type").and_then(Json::as_str).map(str::to_string),
            name: entry.get("name").and_then(Json::as_str).map(str::to_string),
            inputs: parse_params(entry.get("inputs")),
            outputs: parse_params(entry.get("outputs")),
            mutability: entry
                .get("stateMutability")
                .and_then(Json::as_str)
                .map(str::to_string),
            constant: entry.get("constant").and_then(Json::as_bool),
            payable: entry
                .get("payable")
                .and_then(Json::as_bool)
                .unwrap_or(false),
        })
        .collect();
    let sanitized: String = {
        let mut out = String::new();
        let mut in_run = false;
        for c in name.chars() {
            if "!@#$%^&*()_+-=[]{};':\"\\|,.<>/?".contains(c) {
                if !in_run {
                    out.push('_');
                }
                in_run = true;
            } else {
                out.push(c);
                in_run = false;
            }
        }
        out
    };
    Ok(Abi {
        name: sanitized,
        entries,
    })
}

fn signature_param(param: &Param) -> String {
    let indexed = if param.indexed { "indexed " } else { "" };
    let (base, depth) = split_array(&param.ty);
    if base == "tuple" && depth <= 2 {
        let inner: Vec<String> = param.components.iter().map(signature_param).collect();
        let suffix: String = param.ty[base.len()..].to_string();
        return format!("({indexed}{}){suffix}", inner.join(","));
    }
    format!("{indexed}{}", param.ty)
}

fn function_signature(entry: &Entry) -> String {
    let inputs: Vec<String> = entry.inputs.iter().map(signature_param).collect();
    let outputs: Vec<String> = entry.outputs.iter().map(signature_param).collect();
    let outputs = outputs.join(",");
    format!(
        "{}({}){}",
        entry.name.clone().unwrap_or_default(),
        inputs.join(","),
        if outputs.is_empty() {
            String::new()
        } else {
            format!(":({outputs})")
        }
    )
}

/// Whether the parameter is read off an event, a call, or a tuple.
#[derive(Clone, Copy, PartialEq, Eq)]
enum Parent<'a> {
    Event,
    Call,
    Tuple,
    /// A contract function; carries the ABI name, which graph-cli passes where
    /// a parent type goes.
    Function(&'a str),
}

impl Parent<'_> {
    fn label(&self) -> &str {
        match self {
            Parent::Event => "event",
            Parent::Call => "call",
            Parent::Tuple => "tuple",
            Parent::Function(name) => name,
        }
    }
}

struct Generated {
    getter: String,
    classes: Vec<String>,
}

struct AbiGen<'a> {
    abi: &'a Abi,
}

fn getter(name: &str, return_type: &str, body: &str) -> String {
    format!("\n  get {name}(): {return_type} {{\n    {body}\n  }}\n")
}

fn klass(name: &str, extends: Option<&str>, members: &[String], methods: &[String]) -> String {
    let mut out = format!(
        "\nexport class {name}{} {{\n",
        extends.map(|e| format!(" extends {e}")).unwrap_or_default()
    );
    for member in members {
        out.push_str(&format!("  {member}\n"));
    }
    for method in methods {
        out.push_str(method);
    }
    out.push_str("}\n");
    out
}

fn field_name(param: &Param, index: usize, parent: Parent) -> String {
    if param.name.is_empty() {
        if parent == Parent::Event {
            format!("param{index}")
        } else {
            format!("value{index}")
        }
    } else {
        param.name.clone()
    }
}

impl AbiGen<'_> {
    fn input_or_output(
        &self,
        param: &Param,
        index: usize,
        parent_class: &str,
        parent: Parent,
        parent_field: &str,
    ) -> Generated {
        let name = field_name(param, index, parent);
        let value_type = if parent == Parent::Event && param.indexed {
            indexed_input_type(&param.ty)
        } else {
            param.ty.clone()
        };
        if contains_tuple_type(&value_type) {
            return self.tuple_type(param, index, parent_class, parent, parent_field);
        }
        let code = if parent == Parent::Tuple {
            format!("this[{index}]")
        } else {
            format!("this._{}.{parent_field}[{index}].value", parent.label())
        };
        Generated {
            getter: getter(
                &name,
                &asc_type_for_ethereum(&value_type),
                &format!("return {}", ethereum_to_asc(&code, &value_type, "")),
            ),
            classes: vec![],
        }
    }

    fn tuple_type_name(
        &self,
        param: &Param,
        index: usize,
        parent_class: &str,
        parent: Parent,
    ) -> String {
        self.tuple_type(param, index, parent_class, parent, "")
            .name()
    }

    fn tuple_type(
        &self,
        param: &Param,
        index: usize,
        parent_class: &str,
        parent: Parent,
        parent_field: &str,
    ) -> Generated {
        let name = field_name(param, index, parent);
        let identifier = format!("{parent_class}{}", capitalize(&name));
        let class_name = format!(
            "{identifier}{}Struct",
            if parent_field == "outputValues" {
                "Output"
            } else {
                ""
            }
        );
        let code = if parent == Parent::Tuple {
            format!("this[{index}]")
        } else {
            format!("this._{}.{parent_field}[{index}].value", parent.label())
        };
        let value = ethereum_to_asc(&code, &param.ty, &class_name);
        let return_type = if is_tuple_matrix_type(&param.ty) {
            format!("Array<Array<{class_name}>>")
        } else if is_tuple_array_type(&param.ty) {
            format!("Array<{class_name}>")
        } else {
            class_name.clone()
        };
        let body = if is_tuple_type(&param.ty) {
            format!("return changetype<{class_name}>({value})")
        } else {
            format!("return {value}")
        };
        let mut methods = Vec::new();
        let mut classes = Vec::new();
        for (component_index, component) in param.components.iter().enumerate() {
            let generated =
                self.input_or_output(component, component_index, &identifier, Parent::Tuple, "");
            methods.push(generated.getter);
            classes.extend(generated.classes);
        }
        let mut all = vec![klass(&class_name, Some("ethereum.Tuple"), &[], &methods)];
        all.extend(classes);
        Generated {
            getter: getter(&name, &return_type, &body),
            classes: all,
        }
    }

    fn events(&self) -> Vec<String> {
        let events: Vec<&Entry> = self
            .abi
            .entries
            .iter()
            .filter(|entry| entry.kind.as_deref() == Some("event"))
            .collect();
        let aliases = disambiguate(
            events
                .iter()
                .map(|event| event.name.clone().unwrap_or_default())
                .collect(),
        );
        let mut out = Vec::new();
        for (event, class_name) in events.iter().zip(aliases) {
            let params_class = format!("{class_name}__Params");
            let names = disambiguate(
                event
                    .inputs
                    .iter()
                    .enumerate()
                    .map(|(index, input)| {
                        if input.name.is_empty() {
                            format!("param{index}")
                        } else {
                            input.name.clone()
                        }
                    })
                    .collect(),
            );
            let mut methods = vec![format!(
                "\n  constructor(event: {class_name}) {{\n    this._event = event\n  }}\n"
            )];
            let mut tuple_classes = Vec::new();
            for (index, (input, name)) in event.inputs.iter().zip(names).enumerate() {
                let input = Param {
                    name,
                    ..input.clone()
                };
                let generated =
                    self.input_or_output(&input, index, &class_name, Parent::Event, "parameters");
                methods.push(generated.getter);
                tuple_classes.extend(generated.classes);
            }
            out.push(klass(
                &class_name,
                Some("ethereum.Event"),
                &[],
                &[getter(
                    "params",
                    &params_class,
                    &format!("return new {params_class}(this)"),
                )],
            ));
            out.push(klass(
                &params_class,
                None,
                &[format!("_event: {class_name}")],
                &methods,
            ));
            out.extend(tuple_classes);
        }
        out
    }

    fn call_types(&self) -> Vec<String> {
        let functions: Vec<&Entry> = self
            .abi
            .entries
            .iter()
            .filter(|entry| {
                let is_function = matches!(
                    entry.kind.as_deref(),
                    None | Some("constructor") | Some("function") | Some("fallback")
                );
                is_function
                    && (matches!(
                        entry.mutability.as_deref(),
                        Some("nonpayable") | Some("payable")
                    ) || entry.constant == Some(false))
            })
            .collect();
        let aliases = disambiguate(
            functions
                .iter()
                .map(|function| match &function.name {
                    Some(name) if !name.is_empty() => name.clone(),
                    _ if function.kind.as_deref() == Some("constructor") => {
                        "constructor".to_string()
                    }
                    _ => "default".to_string(),
                })
                .collect(),
        );
        let mut out = Vec::new();
        for (function, alias) in functions.iter().zip(aliases) {
            let class_name = format!("{}Call", capitalize(&alias));
            let mut tuple_classes = Vec::new();
            let mut sections = Vec::new();
            for (suffix, params, field) in [
                ("Inputs", &function.inputs, "inputValues"),
                ("Outputs", &function.outputs, "outputValues"),
            ] {
                let holder = format!("{class_name}__{suffix}");
                let names = disambiguate(
                    params
                        .iter()
                        .enumerate()
                        .map(|(index, param)| {
                            if param.name.is_empty() {
                                format!("value{index}")
                            } else {
                                param.name.clone()
                            }
                        })
                        .collect(),
                );
                let mut methods = vec![format!(
                    "\n  constructor(call: {class_name}) {{\n    this._call = call\n  }}\n"
                )];
                for (index, (param, name)) in params.iter().zip(names).enumerate() {
                    let param = Param {
                        name,
                        ..param.clone()
                    };
                    let generated =
                        self.input_or_output(&param, index, &class_name, Parent::Call, field);
                    methods.push(generated.getter);
                    tuple_classes.extend(generated.classes);
                }
                sections.push((
                    suffix,
                    holder.clone(),
                    klass(&holder, None, &[format!("_call: {class_name}")], &methods),
                ));
            }
            let methods: Vec<String> = sections
                .iter()
                .map(|(suffix, holder, _)| {
                    getter(
                        &suffix.to_lowercase(),
                        holder,
                        &format!("return new {holder}(this)"),
                    )
                })
                .collect();
            out.push(klass(&class_name, Some("ethereum.Call"), &[], &methods));
            for (_, _, class) in sections {
                out.push(class);
            }
            out.extend(tuple_classes);
        }
        out
    }

    fn tuple_param_type(&self, param: &Param, index: usize, parent_class: &str) -> String {
        let name =
            || self.tuple_type_name(param, index, parent_class, Parent::Function(&self.abi.name));
        if is_tuple_type(&param.ty) {
            name()
        } else if is_tuple_matrix_type(&param.ty) {
            format!("Array<Array<{}>>", name())
        } else if is_tuple_array_type(&param.ty) {
            format!("Array<{}>", name())
        } else {
            asc_type_for_ethereum(&param.ty)
        }
    }

    fn smart_contract(&self) -> Vec<String> {
        let abi_name = &self.abi.name;
        let mut types: Vec<String> = Vec::new();
        let mut methods = vec![format!(
            "\n  static bind(address: Address): {abi_name} {{\n    return new {abi_name}('{abi_name}', address)\n  }}\n"
        )];
        let functions: Vec<&Entry> = self
            .abi
            .entries
            .iter()
            .filter(|entry| {
                entry.kind.as_deref() == Some("function")
                    && !entry.outputs.is_empty()
                    && (matches!(
                        entry.mutability.as_deref(),
                        Some("view") | Some("pure") | Some("nonpayable") | Some("constant")
                    ) || (entry.mutability.is_none() && !entry.payable))
            })
            .collect();
        let aliases = disambiguate(
            functions
                .iter()
                .map(|function| function.name.clone().unwrap_or_default())
                .collect(),
        );
        for (member, alias) in functions.iter().zip(aliases) {
            let fn_name = member.name.clone().unwrap_or_default();
            let signature = function_signature(member);
            let result_parent = format!("{abi_name}__{alias}Result");
            let outputs: Vec<Param> = disambiguate(
                member
                    .outputs
                    .iter()
                    .enumerate()
                    .map(|(index, output)| {
                        if output.name.is_empty() {
                            format!("value{index}")
                        } else {
                            output.name.clone()
                        }
                    })
                    .collect(),
            )
            .into_iter()
            .zip(&member.outputs)
            .map(|(name, output)| Param {
                name,
                ..output.clone()
            })
            .collect();
            let simple = outputs.len() <= 1;
            let return_type: String;
            if !simple {
                let mut result_methods = vec![format!(
                    "\n  constructor({}) {{\n    {}\n  }}\n",
                    outputs
                        .iter()
                        .enumerate()
                        .map(|(index, output)| format!(
                            "value{index}: {}",
                            self.tuple_param_type(output, index, &result_parent)
                        ))
                        .collect::<Vec<_>>()
                        .join(", "),
                    (0..outputs.len())
                        .map(|index| format!("this.value{index} = value{index}"))
                        .collect::<Vec<_>>()
                        .join("\n    ")
                )];
                result_methods.push(format!(
                    "\n  toMap(): TypedMap<string,ethereum.Value> {{\n    let map = new TypedMap<string,ethereum.Value>();\n    {}\n    return map;\n  }}\n",
                    outputs
                        .iter()
                        .enumerate()
                        .map(|(index, output)| format!(
                            "map.set('value{index}', {})",
                            ethereum_from_asc(&format!("this.value{index}"), &output.ty)
                        ))
                        .collect::<Vec<_>>()
                        .join(";")
                ));
                let members: Vec<String> = outputs
                    .iter()
                    .enumerate()
                    .map(|(index, output)| {
                        format!(
                            "value{index}: {}",
                            self.tuple_param_type(output, index, &result_parent)
                        )
                    })
                    .collect();
                for (index, output) in outputs.iter().enumerate() {
                    let mut chars = output.name.chars();
                    if let Some(first) = chars.next() {
                        result_methods.push(format!(
                            "\n  get{}{}(): {} {{\n    return this.value{index};\n  }}\n",
                            first.to_uppercase(),
                            chars.as_str(),
                            self.tuple_param_type(output, index, &result_parent),
                        ));
                    }
                }
                for (index, output) in outputs.iter().enumerate() {
                    if contains_tuple_type(&output.ty) {
                        types.extend(
                            self.tuple_type(
                                output,
                                index,
                                &result_parent,
                                Parent::Function(abi_name),
                                abi_name,
                            )
                            .classes,
                        );
                    }
                }
                types.push(klass(&result_parent, None, &members, &result_methods));
                return_type = result_parent.clone();
            } else {
                let output = &outputs[0];
                if contains_tuple_type(&output.ty) {
                    let tuple = self.tuple_type(
                        output,
                        0,
                        &result_parent,
                        Parent::Function(abi_name),
                        abi_name,
                    );
                    return_type = if is_tuple_type(&output.ty) {
                        tuple.name()
                    } else {
                        format!("Array<{}>", tuple.name())
                    };
                    types.extend(tuple.classes);
                } else {
                    return_type = asc_type_for_ethereum(&output.ty);
                }
            }

            let inputs: Vec<Param> = disambiguate(
                member
                    .inputs
                    .iter()
                    .enumerate()
                    .map(|(index, input)| {
                        if input.name.is_empty() {
                            format!("param{index}")
                        } else {
                            input.name.clone()
                        }
                    })
                    .collect(),
            )
            .into_iter()
            .zip(&member.inputs)
            .map(|(name, input)| Param {
                name,
                ..input.clone()
            })
            .collect();
            let input_parent = format!("{abi_name}__{alias}Input");
            for (index, input) in inputs.iter().enumerate() {
                if contains_tuple_type(&input.ty) {
                    types.extend(
                        self.tuple_type(
                            input,
                            index,
                            &input_parent,
                            Parent::Function(abi_name),
                            abi_name,
                        )
                        .classes,
                    );
                }
            }
            let params = inputs
                .iter()
                .enumerate()
                .map(|(index, input)| {
                    format!(
                        "{}: {}",
                        input.name,
                        self.tuple_param_type(input, index, &input_parent)
                    )
                })
                .collect::<Vec<_>>()
                .join(", ");
            let arguments = inputs
                .iter()
                .map(|input| ethereum_from_asc(&input.name, &input.ty))
                .collect::<Vec<_>>()
                .join(", ");
            let super_inputs = format!("'{fn_name}', '{signature}', [{arguments}]");

            let tuple_name = |output: &Param, index: usize| {
                self.tuple_type_name(output, index, &result_parent, Parent::Function(abi_name))
            };
            let value_of = |source: &str, output: &Param, index: usize| {
                let internal = if is_tuple_array_type(&output.ty) {
                    tuple_name(output, index)
                } else {
                    String::new()
                };
                ethereum_to_asc(&format!("{source}[{index}]"), &output.ty, &internal)
            };
            let returned = |source: &str| -> String {
                if simple {
                    let output = &outputs[0];
                    let value = value_of(source, output, 0);
                    if is_tuple_type(&output.ty) {
                        format!("changetype<{return_type}>({value})")
                    } else {
                        value
                    }
                } else {
                    let args = outputs
                        .iter()
                        .enumerate()
                        .map(|(index, output)| {
                            let value = value_of(source, output, index);
                            if is_tuple_type(&output.ty) {
                                format!("changetype<{}>({value})", tuple_name(output, index))
                            } else {
                                value
                            }
                        })
                        .collect::<Vec<_>>()
                        .join(", ");
                    let result = format!("new {return_type}({args})");
                    if is_tuple_type(&outputs[0].ty) {
                        format!("changetype<{return_type}>({result})")
                    } else {
                        result
                    }
                }
            };
            methods.push(format!(
                "\n  {alias}({params}): {return_type} {{\n    let result = super.call({super_inputs})\n\n    return ({})\n  }}\n",
                returned("result")
            ));
            methods.push(format!(
                "\n  try_{alias}({params}): ethereum.CallResult<{return_type}> {{\n    let result = super.tryCall({super_inputs})\n    if (result.reverted) {{\n      return new ethereum.CallResult()\n    }}\n    let value = result.value\n    return ethereum.CallResult.fromValue({})\n  }}\n",
                returned("value")
            ));
        }
        types.push(klass(
            abi_name,
            Some("ethereum.SmartContract"),
            &[],
            &methods,
        ));
        types
    }
}

impl Generated {
    fn name(&self) -> String {
        // The first class generated is the tuple's own struct.
        let first = self.classes.first().map(String::as_str).unwrap_or("");
        first
            .split_whitespace()
            .nth(2)
            .unwrap_or_default()
            .to_string()
    }
}

fn indexed_input_type(ty: &str) -> String {
    if ty == "string" || ty == "bytes" || ty == "tuple" || ty.ends_with(']') {
        "bytes32".to_string()
    } else {
        ty.to_string()
    }
}

fn abi_ts(abi: &Abi) -> Result<String> {
    let generator = AbiGen { abi };
    let mut out = String::from(NOTE);
    out.push_str(
        "\nimport { ethereum,JSONValue,TypedMap,Entity,Bytes,Address,BigInt } from \"@graphprotocol/graph-ts\"\n",
    );
    for class in generator
        .events()
        .into_iter()
        .chain(generator.smart_contract())
        .chain(generator.call_types())
    {
        out.push_str(&class);
    }
    Ok(out)
}

