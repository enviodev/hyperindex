//! Bundled `graph codegen`: the `generated/` tree a subgraph's mappings import,
//! written without `@graphprotocol/graph-cli`.
//!
//! graph-cli is often missing, hoisted out of reach, a CommonJS release whose
//! codegen crashes, or impossible to install (dead git dependencies in old
//! lockfiles). The runtime only ever executes the generated code, so what has
//! to match graph-cli is the members a mapping calls and what they do, not the
//! bytes: output is a superset of every graph-cli version's (`loadInBlock`, the
//! derived-field loaders), and unformatted.
//!
//! Ported from graph-cli 0.97's `codegen/{schema,template,typescript,util}.js`,
//! `codegen/types/conversions.js` and `protocols/ethereum/codegen/*.js`.
//!
//! | graph-cli | here |
//! |---|---|
//! | `<DataSource>/<Abi>.ts` | event + `__Params`, tuple struct, contract and call classes |
//! | `templates/<Template>/<Abi>.ts` | the same, for a template's ABIs |
//! | `schema.ts` | one `Entity` subclass per `@entity`, plus a `Loader` per derived type |
//! | `templates.ts` | one `DataSourceTemplate` subclass per template |

use std::collections::{BTreeMap, BTreeSet};
use std::path::{Path, PathBuf};

use anyhow::{anyhow, bail, Context, Result};
use graphql_parser::schema::{Definition, Document, Field, Type, TypeDefinition};
use serde_json::Value as Json;
use serde_yaml::Value as Yaml;

const NOTE: &str = "// THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.\n";

/// How `ENVIO_SUBGRAPH_CODEGEN` picks who builds `generated/`.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum CodegenMode {
    /// The project's graph-cli when it is installed and works, else bundled.
    Auto,
    /// Always bundled.
    Bundled,
    /// Only the project's graph-cli.
    GraphCli,
}

impl CodegenMode {
    pub const ENV_VAR: &'static str = "ENVIO_SUBGRAPH_CODEGEN";

    pub fn from_env() -> Self {
        match std::env::var(Self::ENV_VAR).ok().as_deref() {
            Some("bundled") => CodegenMode::Bundled,
            Some("graph-cli") => CodegenMode::GraphCli,
            _ => CodegenMode::Auto,
        }
    }
}

/// Writes the generated tree for the manifest into `output_dir` and returns the
/// files written, relative to it. Needs only the manifest, its schema and its
/// ABI files: no install, no network.
pub fn generate(manifest_file: &Path, output_dir: &Path) -> Result<Vec<String>> {
    let graph_ts = GraphTs::detect(manifest_file.parent().unwrap_or(Path::new(".")));
    let files = generate_files(manifest_file, graph_ts)?;
    let mut written = Vec::new();
    for (relative, text) in files {
        let target = output_dir.join(&relative);
        if let Some(parent) = target.parent() {
            std::fs::create_dir_all(parent)
                .with_context(|| format!("creating {}", parent.display()))?;
        }
        std::fs::write(&target, text).with_context(|| format!("writing {}", target.display()))?;
        written.push(relative);
    }
    Ok(written)
}

/// The generated tree in memory: relative path to file text.
pub fn generate_files(manifest_file: &Path, graph_ts: GraphTs) -> Result<BTreeMap<String, String>> {
    let text = std::fs::read_to_string(manifest_file)
        .with_context(|| format!("reading {}", manifest_file.display()))?;
    let manifest: Yaml = serde_yaml::from_str(&text)
        .with_context(|| format!("parsing {}", manifest_file.display()))?;
    let base = manifest_file.parent().unwrap_or(Path::new("."));
    let mut files = BTreeMap::new();

    let schema_file = manifest
        .get("schema")
        .and_then(|schema| schema.get("file"))
        .and_then(Yaml::as_str)
        .unwrap_or("schema.graphql");
    let schema_text = std::fs::read_to_string(base.join(schema_file))
        .with_context(|| format!("reading the schema {schema_file}"))?;
    files.insert("schema.ts".to_string(), schema_ts(&schema_text, graph_ts)?);

    let list = |key: &str| -> Vec<&Yaml> {
        manifest
            .get(key)
            .and_then(Yaml::as_sequence)
            .map(|seq| seq.iter().collect())
            .unwrap_or_default()
    };

    for source in list("dataSources") {
        let kind = source.get("kind").and_then(Yaml::as_str).unwrap_or("");
        if !kind.starts_with("ethereum") {
            continue;
        }
        let Some(name) = source.get("name").and_then(Yaml::as_str) else {
            continue;
        };
        for (abi_name, file) in mapping_abis(source) {
            let abi = load_abi(&abi_name, &base.join(&file))?;
            files.insert(format!("{name}/{}.ts", abi.name), abi_ts(&abi)?);
        }
    }

    let mut templates = String::new();
    let mut template_imports: BTreeSet<&str> = BTreeSet::new();
    for template in list("templates") {
        let kind = template.get("kind").and_then(Yaml::as_str).unwrap_or("");
        let Some(name) = template.get("name").and_then(Yaml::as_str) else {
            continue;
        };
        for (abi_name, file) in mapping_abis(template) {
            let abi = load_abi(&abi_name, &base.join(&file))?;
            files.insert(format!("templates/{name}/{}.ts", abi.name), abi_ts(&abi)?);
        }
        if kind.starts_with("ethereum") {
            template_imports.insert("Address");
            templates.push_str(&template_class(
                name,
                "address",
                "Address",
                "address.toHex()",
            ));
        } else if kind == "file/ipfs" || kind == "file/arweave" {
            templates.push_str(&template_class(name, "cid", "string", "cid"));
        }
    }
    if !templates.is_empty() {
        let mut imports: Vec<&str> = template_imports.into_iter().collect();
        imports.extend(["DataSourceTemplate", "DataSourceContext"]);
        files.insert(
            "templates.ts".to_string(),
            format!(
                "{NOTE}\nimport {{ {} }} from \"@graphprotocol/graph-ts\"\n{templates}",
                imports.join(",")
            ),
        );
    }
    Ok(files)
}

fn mapping_abis(source: &Yaml) -> Vec<(String, String)> {
    source
        .get("mapping")
        .and_then(|mapping| mapping.get("abis"))
        .and_then(Yaml::as_sequence)
        .map(|abis| {
            abis.iter()
                .filter_map(|abi| {
                    Some((
                        abi.get("name")?.as_str()?.to_string(),
                        abi.get("file")?.as_str()?.to_string(),
                    ))
                })
                .collect()
        })
        .unwrap_or_default()
}

fn template_class(name: &str, param: &str, param_type: &str, argument: &str) -> String {
    format!(
        "\nexport class {name} extends DataSourceTemplate {{\n  static create({param}: {param_type}): void {{\n    DataSourceTemplate.create('{name}', [{argument}])\n  }}\n\n  static createWithContext({param}: {param_type}, context: DataSourceContext): void {{\n    DataSourceTemplate.createWithContext('{name}', [{argument}], context)\n  }}\n}}\n"
    )
}

/// What the project's own `@graphprotocol/graph-ts` exports. graph-cli emits
/// what its own release knows, and AssemblyScript compiles only what a mapping
/// reaches, so extra methods are harmless but an extra import or a changed
/// signature (`envio dev`'s `graph build` type check) is not; the
/// runtime's shim has all of it, so without a graph-ts everything is on.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct GraphTs {
    /// `Int8` is exported (graph-ts 0.31+).
    pub int8: bool,
    /// `store.loadRelated`, behind the derived-field loaders (graph-ts 0.35+);
    /// without it a derived field reads like any other.
    pub related: bool,
    /// `Value.displayData`, in `save()`'s assertion message.
    pub display: bool,
}

impl GraphTs {
    pub const ALL: GraphTs = GraphTs {
        int8: true,
        related: true,
        display: true,
    };

    /// The graph-ts Node would resolve from the manifest's directory.
    pub fn detect(manifest_dir: &Path) -> GraphTs {
        let Ok(start) = std::fs::canonicalize(manifest_dir) else {
            return GraphTs::ALL;
        };
        for dir in start.ancestors() {
            let package = dir.join("node_modules/@graphprotocol/graph-ts");
            if !package.join("package.json").is_file() {
                continue;
            }
            let mut text = String::new();
            for file in [
                "index.ts",
                "common/numbers.ts",
                "common/value.ts",
                "common/collections.ts",
            ] {
                if let Ok(source) = std::fs::read_to_string(package.join(file)) {
                    text.push_str(&source);
                }
            }
            return GraphTs {
                int8: text.contains("Int8"),
                related: text.contains("loadRelated"),
                display: text.contains("displayData"),
            };
        }
        GraphTs::ALL
    }
}

