fn reserved(name: &str) -> String {
    if RESERVED_WORDS.contains(&name) {
        format!("{name}_")
    } else {
        name.to_string()
    }
}

/// graph-cli's `disambiguateNames`: reserved words get a `_`, then the second
/// and later uses of a name a counter (`transfer`, `transfer1`, `transfer2`).
fn disambiguate(names: Vec<String>) -> Vec<String> {
    let mut seen: BTreeMap<String, usize> = BTreeMap::new();
    names
        .into_iter()
        .map(|name| {
            let name = reserved(&name);
            match seen.get_mut(&name) {
                None => {
                    seen.insert(name.clone(), 1);
                    name
                }
                Some(counter) => {
                    let unique = format!("{name}{counter}");
                    *counter += 1;
                    unique
                }
            }
        })
        .collect()
}

fn capitalize(name: &str) -> String {
    let mut chars = name.chars();
    match chars.next() {
        Some(first) => first.to_uppercase().chain(chars).collect(),
        None => String::new(),
    }
}

