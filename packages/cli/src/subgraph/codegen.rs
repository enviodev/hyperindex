    /// `Class.member` for every class member a graph-cli tree declares.
    fn surface(text: &str) -> BTreeSet<String> {
        let class = regex::Regex::new(r"^export class (\w+)").unwrap();
        let member = regex::Regex::new(r"^  (?:static )?(?:get |set )?(\w+)\(").unwrap();
        let mut current = String::new();
        let mut out = BTreeSet::new();
        for line in text.lines() {
            if let Some(found) = class.captures(line) {
                current = found[1].to_string();
                out.insert(current.clone());
            } else if let Some(found) = member.captures(line) {
                let kind = if line.trim_start().starts_with("static ") {
                    "static "
                } else if line.trim_start().starts_with("get ") {
                    "get "
                } else if line.trim_start().starts_with("set ") {
                    "set "
                } else {
                    ""
                };
                out.insert(format!("{current}.{kind}{}", &found[1]));
            }
        }
        out
    }

