#[derive(Clone, Copy, PartialEq, Eq)]
enum IdKind {
    Bytes,
    Int8,
    Str,
}

impl IdKind {
    fn type_name(self) -> &'static str {
        match self {
            IdKind::Bytes => "Bytes",
            IdKind::Int8 => "Int8",
            IdKind::Str => "string",
        }
    }
    fn gql_name(self) -> &'static str {
        match self {
            IdKind::Bytes => "Bytes",
            IdKind::Int8 => "Int8",
            IdKind::Str => "String",
        }
    }
    fn value_from(self) -> &'static str {
        match self {
            IdKind::Bytes => "Value.fromBytes(id)",
            IdKind::Int8 => "Value.fromI64(id)",
            IdKind::Str => "Value.fromString(id)",
        }
    }
    fn value_kind(self) -> &'static str {
        match self {
            IdKind::Bytes => "ValueKind.BYTES",
            IdKind::Int8 => "ValueKind.INT8",
            IdKind::Str => "ValueKind.STRING",
        }
    }
    fn value_to_string(self) -> &'static str {
        match self {
            IdKind::Bytes => "id.toBytes().toHexString()",
            IdKind::Int8 => "id.toI64().toString()",
            IdKind::Str => "id.toString()",
        }
    }
    fn to_string_expr(self) -> &'static str {
        match self {
            IdKind::Bytes => "id.toHexString()",
            IdKind::Int8 => "id.toString()",
            IdKind::Str => "id",
        }
    }
}

type SchemaField<'a> = Field<'a, String>;

fn named_type<'t>(ty: &'t Type<'_, String>) -> &'t str {
    match ty {
        Type::NamedType(name) => name,
        Type::ListType(inner) | Type::NonNullType(inner) => named_type(inner),
    }
}

fn id_kind(fields: &[SchemaField<'_>]) -> IdKind {
    let Some(field) = fields.iter().find(|field| field.name == "id") else {
        return IdKind::Str;
    };
    match &field.field_type {
        Type::NonNullType(inner) => match &**inner {
            Type::NamedType(name) if name == "Bytes" => IdKind::Bytes,
            Type::NamedType(name) if name == "Int8" => IdKind::Int8,
            _ => IdKind::Str,
        },
        _ => IdKind::Str,
    }
}

/// An AssemblyScript type as graph-cli models it.
enum Ty {
    Named(String),
    Array(Box<Ty>),
    Nullable(Box<Ty>),
}

impl std::fmt::Display for Ty {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            Ty::Named(name) => write!(f, "{name}"),
            Ty::Array(inner) => write!(f, "Array<{inner}>"),
            Ty::Nullable(inner) => write!(f, "{inner} | null"),
        }
    }
}

/// The value graph-cli 0.22-0.29 set a non-nullable field to in a new entity
/// (ASSEMBLYSCRIPT_TO_VALUE's initial values); `None` for a type it had no
/// conversion for.
fn zero_value(ty: &Ty) -> Option<String> {
    let value = match ty {
        Ty::Array(inner) => {
            let method = match inner.as_ref() {
                Ty::Named(asc) => match asc.as_str() {
                    "Bytes" | "Address" => "fromBytesArray",
                    "boolean" => "fromBooleanArray",
                    "i32" => "fromI32Array",
                    "BigInt" => "fromBigIntArray",
                    "string" => "fromStringArray",
                    "BigDecimal" => "fromBigDecimalArray",
                    _ => return None,
                },
                Ty::Nullable(element) if matches!(element.as_ref(), Ty::Named(asc) if asc == "string") => {
                    "fromStringArray"
                }
                _ => return None,
            };
            format!("Value.{method}(new Array(0))")
        }
        Ty::Named(asc) => match asc.as_str() {
            "Bytes" => "Value.fromBytes(Bytes.empty())".to_string(),
            "boolean" => "Value.fromBoolean(false)".to_string(),
            "i32" => "Value.fromI32(0)".to_string(),
            "BigInt" => "Value.fromBigInt(BigInt.zero())".to_string(),
            "string" => "Value.fromString('')".to_string(),
            "BigDecimal" => "Value.fromBigDecimal(BigDecimal.zero())".to_string(),
            _ => return None,
        },
        Ty::Nullable(_) => return None,
    };
    Some(value)
}

fn is_primitive(name: &str) -> bool {
    matches!(
        name,
        "boolean"
            | "u8"
            | "i8"
            | "u16"
            | "i16"
            | "u32"
            | "i32"
            | "u64"
            | "i64"
            | "f32"
            | "f64"
            | "usize"
            | "isize"
    )
}

struct SchemaGen<'a> {
    document: &'a Document<'a, String>,
    graph_ts: GraphTs,
}

impl<'a> SchemaGen<'a> {
    fn definitions(&self) -> impl Iterator<Item = &TypeDefinition<'a, String>> {
        self.document
            .definitions
            .iter()
            .filter_map(|definition| match definition {
                Definition::TypeDefinition(def) => Some(def),
                _ => None,
            })
    }

    fn entities(&self) -> impl Iterator<Item = &graphql_parser::schema::ObjectType<'a, String>> {
        self.definitions().filter_map(|def| match def {
            TypeDefinition::Object(object)
                if object.directives.iter().any(|d| d.name == "entity") =>
            {
                Some(object)
            }
            _ => None,
        })
    }

    fn object(&self, name: &str) -> Option<&graphql_parser::schema::ObjectType<'a, String>> {
        self.definitions().find_map(|def| match def {
            TypeDefinition::Object(object) if object.name == name => Some(object),
            _ => None,
        })
    }

    fn interfaces(&self) -> BTreeSet<&str> {
        self.definitions()
            .filter_map(|def| match def {
                TypeDefinition::Interface(interface) => Some(interface.name.as_str()),
                _ => None,
            })
            .collect()
    }

    /// A reference to another type takes the type of that type's id.
    fn resolve(&self, name: &str) -> String {
        for def in self.definitions() {
            match def {
                TypeDefinition::Object(object)
                    if object.name == name
                        && object.directives.iter().any(|d| d.name == "entity") =>
                {
                    return id_kind(&object.fields).type_name().to_string();
                }
                TypeDefinition::Interface(interface) if interface.name == name => {
                    return id_kind(&interface.fields).type_name().to_string();
                }
                _ => {}
            }
        }
        name.to_string()
    }

    fn value_type(&self, ty: &Type<'_, String>) -> String {
        match ty {
            Type::NonNullType(inner) => self.value_type(inner),
            Type::ListType(inner) => format!("[{}]", self.value_type(inner)),
            Type::NamedType(name) => self.resolve(name),
        }
    }

    fn ty(&self, ty: &Type<'_, String>, nullable: bool) -> Ty {
        match ty {
            Type::NonNullType(inner) => self.ty(inner, false),
            Type::ListType(inner) => {
                let array = Ty::Array(Box::new(self.ty(inner, true)));
                if nullable {
                    Ty::Nullable(Box::new(array))
                } else {
                    array
                }
            }
            Type::NamedType(name) => {
                let asc = asc_type_for_value(&self.resolve(name));
                if nullable && !is_primitive(&asc) {
                    Ty::Nullable(Box::new(Ty::Named(asc)))
                } else {
                    Ty::Named(asc)
                }
            }
        }
    }

    fn is_derived(&self, field: &SchemaField<'_>) -> bool {
        self.graph_ts.related && field.directives.iter().any(|d| d.name == "derivedFrom")
    }

    fn entity_type(&self, object: &graphql_parser::schema::ObjectType<'a, String>) -> String {
        let name = &object.name;
        let id = id_kind(&object.fields);
        let defaults: String = if self.graph_ts.constructor_defaults {
            object
                .fields
                .iter()
                .filter(|field| field.name != "id")
                .filter(|field| matches!(field.field_type, Type::NonNullType(_)))
                .filter(|field| !field.directives.iter().any(|d| d.name == "derivedFrom"))
                .filter_map(|field| {
                    let value = zero_value(&self.ty(&field.field_type, true))?;
                    Some(format!("\n    this.set('{}', {value})", field.name))
                })
                .collect()
        } else {
            String::new()
        };
        let mut methods = vec![format!(
            "\n  constructor(id: {}) {{\n    super()\n    this.set('id', {}){defaults}\n  }}\n",
            id.type_name(),
            id.value_from()
        )];
        let assertion = if self.graph_ts.display {
            format!(
                "`Entities of type {name} must have an ID of type {gql} but the id '${{id.displayData()}}' is of type ${{id.displayKind()}}`",
                gql = id.gql_name()
            )
        } else {
            format!("'Cannot save {name} entity with non-{gql} ID. Considering using .toHex() to convert the \"id\" to a string.'", gql = id.gql_name())
        };
        methods.push(format!(
            "\n  save(): void {{\n    let id = this.get('id')\n    assert(id != null,\n           'Cannot save {name} entity without an ID')\n    if (id) {{\n      assert(id.kind == {kind},\n             {assertion})\n      store.set('{name}', {to_string}, this)\n    }}\n  }}\n",
            kind = id.value_kind(),
            to_string = id.value_to_string(),
        ));
        methods.push(format!(
            "\n  static loadInBlock(id: {ty}): {name} | null {{\n    return changetype<{name} | null>(store.get_in_block('{name}', {s}))\n  }}\n",
            ty = id.type_name(),
            s = id.to_string_expr()
        ));

        methods.push(format!(
            "\n  static load(id: {ty}): {name} | null {{\n    return changetype<{name} | null>(store.get('{name}', {s}))\n  }}\n",
            ty = id.type_name(),
            s = id.to_string_expr()
        ));
        for field in &object.fields {
            if let Some(getter) = self.field_getter(object, field) {
                methods.push(getter);
            }
            if let Some(setter) = self.field_setter(field) {
                methods.push(setter);
            }
        }
        klass(name, Some("Entity"), &[], &methods)
    }

    fn field_getter(
        &self,
        entity: &graphql_parser::schema::ObjectType<'a, String>,
        field: &SchemaField<'_>,
    ) -> Option<String> {
        let name = &field.name;
        let safe = reserved(name);
        if self.is_derived(field) {
            // Only a derived field whose type is an object type gets a getter.
            self.object(named_type(&field.field_type))?;
            let loader = format!("{}Loader", named_type(&field.field_type));
            let id_is_bytes = id_kind(&entity.fields) == IdKind::Bytes;
            let to_value = if id_is_bytes {
                ".toBytes().toHexString()"
            } else {
                ".toString()"
            };
            return Some(getter(
                &safe,
                &loader,
                &format!(
                    "return new {loader}('{}', this.get('id')!{to_value}, '{name}')",
                    entity.name
                ),
            ));
        }
        let value_type = self.value_type(&field.field_type);
        let return_type = self.ty(&field.field_type, true);
        let to_asc = value_to_asc("value", &value_type);
        let body = match &return_type {
            Ty::Nullable(_) => format!(
                "let value = this.get('{name}')\n    if (!value || value.kind == ValueKind.NULL) {{\n      return null\n    }} else {{\n      return {to_asc}\n    }}"
            ),
            other => {
                let default = match other {
                    Ty::Named(asc) if is_primitive(asc) => {
                        format!("return {}", if asc == "boolean" { "false" } else { "0" })
                    }
                    _ => "throw new Error('Cannot return null for a required field.')".to_string(),
                };
                format!(
                    "let value = this.get('{name}')\n    if (!value || value.kind == ValueKind.NULL) {{\n      {default}\n    }} else {{\n      return {to_asc}\n    }}"
                )
            }
        };
        Some(getter(&safe, &return_type.to_string(), &body))
    }

    fn field_setter(&self, field: &SchemaField) -> Option<String> {
        if self.is_derived(field) {
            return None;
        }
        let name = &field.name;
        let safe = reserved(name);
        let value_type = self.value_type(&field.field_type);
        let param_type = self.ty(&field.field_type, true);
        let (nullable, type_string) = match &param_type {
            Ty::Nullable(inner) => (true, inner.to_string()),
            other => (false, other.to_string()),
        };
        let body = if nullable {
            format!(
                "if ({}) {{\n      this.unset('{name}')\n    }} else {{\n      this.set('{name}', {})\n    }}",
                if self.graph_ts.unset_only_null {
                    "value === null"
                } else {
                    "!value"
                },
                value_from_asc(&format!("<{type_string}>value"), &value_type)
            )
        } else {
            format!(
                "this.set('{name}', {})",
                value_from_asc("value", &value_type)
            )
        };
        Some(format!(
            "\n  set {safe}(value: {param_type}) {{\n    {body}\n  }}\n"
        ))
    }

    fn derived_loaders(&self) -> Vec<String> {
        let interfaces = self.interfaces();
        let mut type_names: Vec<String> = Vec::new();
        for entity in self.entities() {
            for field in &entity.fields {
                if self.is_derived(field) {
                    let name = named_type(&field.field_type).to_string();
                    if !type_names.contains(&name) {
                        type_names.push(name);
                    }
                }
            }
        }
        type_names
            .into_iter()
            .filter(|name| !interfaces.contains(name.as_str()))
            .map(|name| {
                klass(
                    &format!("{name}Loader"),
                    Some("Entity"),
                    &[
                        "_entity: string".to_string(),
                        "_field: string".to_string(),
                        "_id: string".to_string(),
                    ],
                    &[
                        "\n  constructor(entity: string, id: string, field: string) {\n    super();\n    this._entity = entity;\n    this._id = id;\n    this._field = field;\n  }\n".to_string(),
                        format!("\n  load(): {name}[] {{\n    let value = store.loadRelated(this._entity, this._id, this._field);\n    return changetype<{name}[]>(value);\n  }}\n"),
                    ],
                )
            })
            .collect()
    }
}

fn schema_ts(schema_text: &str, graph_ts: GraphTs) -> Result<String> {
    let document: Document<'_, String> = graphql_parser::parse_schema(schema_text)
        .map_err(|error| anyhow!("Failed to parse the GraphQL schema: {error}"))?;
    let generator = SchemaGen {
        document: &document,
        graph_ts,
    };
    let mut out = String::from(NOTE);
    out.push_str(&format!(
        "\nimport {{ TypedMap,Entity,Value,ValueKind,store,Bytes,BigInt,BigDecimal{} }} from \"@graphprotocol/graph-ts\"\n",
        if graph_ts.int8 { ",Int8" } else { "" }
    ));
    for entity in generator.entities() {
        out.push_str(&generator.entity_type(entity));
    }
    if graph_ts.related {
        for loader in generator.derived_loaders() {
            out.push_str(&loader);
        }
    }
    Ok(out)
}

