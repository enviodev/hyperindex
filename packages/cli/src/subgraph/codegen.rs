/// Where bundled codegen writes: the directory the mappings import from.
pub fn output_dir_for(root: &Path, manifest_file: &Path) -> Result<PathBuf> {
    let text = std::fs::read_to_string(manifest_file)
        .with_context(|| format!("reading {}", manifest_file.display()))?;
    let manifest: Yaml = serde_yaml::from_str(&text)?;
    let mut mapping_files = Vec::new();
    let base = manifest_file.parent().unwrap_or(Path::new("."));
    for key in ["dataSources", "templates"] {
        for source in manifest
            .get(key)
            .and_then(Yaml::as_sequence)
            .into_iter()
            .flatten()
        {
            if let Some(file) = source
                .get("mapping")
                .and_then(|mapping| mapping.get("file"))
                .and_then(Yaml::as_str)
            {
                let absolute = base.join(file);
                let relative = absolute
                    .strip_prefix(root)
                    .map(Path::to_path_buf)
                    .unwrap_or(absolute);
                mapping_files.push(relative.to_string_lossy().into_owned());
            }
        }
    }
    if mapping_files.is_empty() {
        bail!("{} lists no mapping files", manifest_file.display());
    }
    let dir = super::generated_dir(root, &mapping_files);
    let mut normalized = PathBuf::new();
    for part in dir.components() {
        match part {
            std::path::Component::ParentDir => {
                normalized.pop();
            }
            std::path::Component::CurDir => {}
            other => normalized.push(other),
        }
    }
    Ok(normalized)
}

