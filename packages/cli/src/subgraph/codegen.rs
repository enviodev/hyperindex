fn asc_type_for_value(value_type: &str) -> String {
    let array = |inner: &str| format!("Array<{inner}>");
    match value_type {
        "[Bytes]" => array("Bytes"),
        "[Boolean]" => array("boolean"),
        "[Int]" => array("i32"),
        "[Int8]" | "[Timestamp]" => array("i64"),
        "[BigInt]" => array("BigInt"),
        "[ID]" | "[String]" => array("string"),
        "[BigDecimal]" => array("BigDecimal"),
        other if other.contains('[') => array("string"),
        "Bytes" => "Bytes".into(),
        "Boolean" => "boolean".into(),
        "Int" => "i32".into(),
        "Int8" | "Timestamp" => "i64".into(),
        "BigInt" => "BigInt".into(),
        "BigDecimal" => "BigDecimal".into(),
        _ => "string".into(),
    }
}

fn value_to_asc(code: &str, value_type: &str) -> String {
    let method = match value_type {
        "[Bytes]" => "toBytesArray",
        "[Boolean]" => "toBooleanArray",
        "[Int]" => "toI32Array",
        "[Int8]" => "toI64Array",
        "[Timestamp]" => "toTimestampArray",
        "[BigInt]" => "toBigIntArray",
        "[ID]" | "[String]" => "toStringArray",
        "[BigDecimal]" => "toBigDecimalArray",
        other if other.contains('[') => "toStringArray",
        "Bytes" => "toBytes",
        "Boolean" => "toBoolean",
        "Int" => "toI32",
        "Int8" => "toI64",
        "BigInt" => "toBigInt",
        "BigDecimal" => "toBigDecimal",
        "Timestamp" => "toTimestamp",
        _ => "toString",
    };
    format!("{code}.{method}()")
}

fn value_from_asc(code: &str, value_type: &str) -> String {
    let method = match value_type {
        "[[Bytes]]" => "fromBytesMatrix",
        "[[Boolean]]" => "fromBooleanMatrix",
        "[[Int]]" => "fromI32Matrix",
        "[[Int8]]" => "fromI64Matrix",
        "[[Timestamp]]" => "fromTimestampMatrix",
        "[[BigInt]]" => "fromBigIntMatrix",
        "[[BigDecimal]]" => "fromBigDecimalMatrix",
        other if other.starts_with("[[") => "fromStringMatrix",
        "[Bytes]" => "fromBytesArray",
        "[Boolean]" => "fromBooleanArray",
        "[Int]" => "fromI32Array",
        "[Int8]" => "fromI64Array",
        "[Timestamp]" => "fromTimestampArray",
        "[BigInt]" => "fromBigIntArray",
        "[BigDecimal]" => "fromBigDecimalArray",
        other if other.contains('[') => "fromStringArray",
        "Bytes" => "fromBytes",
        "Boolean" => "fromBoolean",
        "Int" => "fromI32",
        "Int8" => "fromI64",
        "Timestamp" => "fromTimestamp",
        "BigInt" => "fromBigInt",
        "BigDecimal" => "fromBigDecimal",
        _ => "fromString",
    };
    format!("Value.{method}({code})")
}

