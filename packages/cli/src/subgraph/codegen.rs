#[derive(Clone, Copy, PartialEq, Eq)]
enum Scalar {
    Address,
    Bool,
    Bytes,
    I32,
    BigInt,
    Str,
    Tuple,
}

/// `base[..][..]` split into the element type and its array depth.
fn split_array(ty: &str) -> (&str, usize) {
    let mut base = ty;
    let mut depth = 0;
    while base.ends_with(']') {
        match base.rfind('[') {
            Some(open) => {
                base = &base[..open];
                depth += 1;
            }
            None => break,
        }
    }
    (base, depth)
}

fn bits_of(base: &str, prefix: &str) -> Option<u32> {
    let rest = base.strip_prefix(prefix)?;
    if rest.is_empty() {
        return Some(256);
    }
    rest.parse().ok()
}

fn scalar_of(base: &str) -> Scalar {
    match base {
        "address" => Scalar::Address,
        "bool" => Scalar::Bool,
        "byte" | "bytes" => Scalar::Bytes,
        "string" => Scalar::Str,
        "tuple" => Scalar::Tuple,
        _ if base.starts_with("bytes") => Scalar::Bytes,
        _ => {
            if let Some(bits) = bits_of(base, "uint") {
                if bits <= 24 {
                    Scalar::I32
                } else {
                    Scalar::BigInt
                }
            } else if let Some(bits) = bits_of(base, "int") {
                if bits <= 32 {
                    Scalar::I32
                } else {
                    Scalar::BigInt
                }
            } else {
                // graph-cli refuses a type it has no row for; a mapping can
                // still use the rest of the ABI.
                Scalar::Str
            }
        }
    }
}

fn scalar_asc(scalar: Scalar) -> &'static str {
    match scalar {
        Scalar::Address => "Address",
        Scalar::Bool => "boolean",
        Scalar::Bytes => "Bytes",
        Scalar::I32 => "i32",
        Scalar::BigInt => "BigInt",
        Scalar::Str => "string",
        Scalar::Tuple => "ethereum.Tuple",
    }
}

fn scalar_word(scalar: Scalar) -> &'static str {
    match scalar {
        Scalar::Address => "Address",
        Scalar::Bool => "Boolean",
        Scalar::Bytes => "Bytes",
        Scalar::I32 => "I32",
        Scalar::BigInt => "BigInt",
        Scalar::Str => "String",
        Scalar::Tuple => "Tuple",
    }
}

fn asc_type_for_ethereum(ty: &str) -> String {
    let (base, depth) = split_array(ty);
    let mut asc = scalar_asc(scalar_of(base)).to_string();
    for _ in 0..depth {
        asc = format!("Array<{asc}>");
    }
    asc
}

/// `ethereumToAsc`: the expression reading a `ethereum.Value` as its AS type.
fn ethereum_to_asc(code: &str, ty: &str, internal: &str) -> String {
    let (base, depth) = split_array(ty);
    let scalar = scalar_of(base);
    let word = scalar_word(scalar);
    let generic = if scalar == Scalar::Tuple && depth > 0 {
        format!("<{internal}>")
    } else {
        String::new()
    };
    match depth {
        0 => format!("{code}.to{word}()"),
        1 => format!("{code}.to{word}Array{generic}()"),
        _ => format!("{code}.to{word}Matrix{generic}()"),
    }
}

/// `ethereumFromAsc`: the expression writing an AS value as an `ethereum.Value`.
fn ethereum_from_asc(code: &str, ty: &str) -> String {
    let (base, depth) = split_array(ty);
    let scalar = scalar_of(base);
    let signed = base.starts_with("int");
    let kind = match scalar {
        Scalar::Address => "Address",
        Scalar::Bool => "Boolean",
        Scalar::Bytes if base == "bytes" => "Bytes",
        Scalar::Bytes => "FixedBytes",
        Scalar::I32 => "I32",
        Scalar::BigInt if signed => "SignedBigInt",
        Scalar::BigInt => "UnsignedBigInt",
        Scalar::Str => "String",
        Scalar::Tuple => "Tuple",
    };
    match depth {
        0 if scalar == Scalar::I32 && !signed => {
            format!("ethereum.Value.fromUnsignedBigInt(BigInt.fromI32({code}))")
        }
        0 => format!("ethereum.Value.from{kind}({code})"),
        1 => format!("ethereum.Value.from{kind}Array({code})"),
        _ => format!("ethereum.Value.from{kind}Matrix({code})"),
    }
}

fn is_tuple_type(ty: &str) -> bool {
    ty == "tuple"
}
fn is_tuple_array_type(ty: &str) -> bool {
    split_array(ty) == ("tuple", 1)
}
fn is_tuple_matrix_type(ty: &str) -> bool {
    split_array(ty) == ("tuple", 2)
}
fn contains_tuple_type(ty: &str) -> bool {
    is_tuple_type(ty) || is_tuple_array_type(ty) || is_tuple_matrix_type(ty)
}

