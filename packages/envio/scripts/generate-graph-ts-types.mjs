/**
 * Generates TypeScript declarations for `@graphprotocol/graph-ts` from the real
 * package, so the shim can be type-checked against the surface a subgraph
 * developer codes against.
 *
 * graph-ts is AssemblyScript: `u64`, `i32` and `usize` are not TypeScript
 * types, so `tsc` cannot read it. Two things make it readable:
 *
 *   1. AS primitives and decorators are rewritten to their TS equivalents.
 *      Signatures survive this exactly; only bodies would be affected, and
 *   2. declarations are emitted with `--noCheck`, so the bodies — which mix
 *      integer widths in ways AS allows and TS doesn't — are never checked.
 *
 * Run after bumping the pinned graph-ts, and commit the result.
 *
 *   node scripts/generate-graph-ts-types.mjs
 */

import { execFileSync } from "node:child_process";
import { cpSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { createRequire } from "node:module";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { readdirSync, statSync } from "node:fs";

const here = dirname(fileURLToPath(import.meta.url));
const packageRoot = resolve(here, "..");
const outDir = join(packageRoot, "src", "subgraph", "graph-ts-types");
// Outside the package: tsc excludes node_modules from `include` by default.
const workDir = mkdtempSync(join(tmpdir(), "graph-ts-types-"));

const require = createRequire(import.meta.url);
const graphTs = dirname(require.resolve("@graphprotocol/graph-ts/package.json"));
const version = JSON.parse(readFileSync(join(graphTs, "package.json"), "utf8")).version;

const AS_PRIMITIVES = {
  i8: "number",
  u8: "number",
  i16: "number",
  u16: "number",
  i32: "number",
  u32: "number",
  f32: "number",
  f64: "number",
  usize: "number",
  isize: "number",
  i64: "bigint",
  u64: "bigint",
  bool: "boolean",
};

const primitives = new RegExp(`\\b(${Object.keys(AS_PRIMITIVES).join("|")})\\b`, "g");
const decorators = /^\s*@(operator(\.prefix|\.postfix)?|inline|external|global|unmanaged|lazy|unsafe)\b.*$/gm;

function rewrite(dir) {
  for (const entry of readdirSync(dir)) {
    const path = join(dir, entry);
    if (statSync(path).isDirectory()) {
      rewrite(path);
    } else if (entry.endsWith(".ts")) {
      const source = readFileSync(path, "utf8")
        .replace(decorators, "")
        .replace(primitives, (name) => AS_PRIMITIVES[name]);
      writeFileSync(path, source);
    }
  }
}

for (const entry of ["index.ts", "common", "chain", "global", "helper-functions.ts"]) {
  cpSync(join(graphTs, entry), join(workDir, entry), { recursive: true });
}
rewrite(workDir);

writeFileSync(
  join(workDir, "as-builtins.d.ts"),
  [
    "declare function changetype<T>(value: unknown): T;",
    "declare function assert<T>(value: T, message?: string): T;",
    "declare function unchecked<T>(value: T): T;",
    "",
  ].join("\n"),
);

writeFileSync(
  join(workDir, "tsconfig.json"),
  JSON.stringify(
    {
      compilerOptions: {
        target: "esnext",
        module: "preserve",
        moduleResolution: "bundler",
        strict: false,
        skipLibCheck: true,
        declaration: true,
        emitDeclarationOnly: true,
        rootDir: ".",
        outDir: "out",
      },
      include: ["."],
    },
    null,
    2,
  ),
);

const tsc = require.resolve("typescript/bin/tsc");
execFileSync(process.execPath, [tsc, "-p", join(workDir, "tsconfig.json"), "--noCheck"], {
  stdio: "inherit",
});

rmSync(outDir, { recursive: true, force: true });
cpSync(join(workDir, "out"), outDir, { recursive: true });
writeFileSync(
  join(outDir, "VERSION"),
  `@graphprotocol/graph-ts ${version}\nGenerated by scripts/generate-graph-ts-types.mjs\n`,
);

console.log(`Wrote declarations for @graphprotocol/graph-ts ${version} to ${outDir}`);
